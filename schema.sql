create or replace function public.validate_coupon(p_code text,p_amount numeric)
returns table(code text,type text,value numeric,min_amount numeric,max_discount numeric,discount numeric)
language plpgsql security definer set search_path=public
as $$
declare c public.coupons; d numeric;
begin
  select * into c from public.coupons where upper(code)=upper(trim(p_code)) and active=true and (starts_at is null or starts_at<=now()) and (expires_at is null or expires_at>now()) and (usage_limit is null or used_count<usage_limit) limit 1;
  if not found or p_amount < c.min_amount then return; end if;
  if c.type='percent' then d:=p_amount*c.value/100; else d:=c.value; end if;
  if c.max_discount is not null then d:=least(d,c.max_discount); end if;
  d:=least(greatest(d,0),p_amount);
  return query select c.code,c.type,c.value,c.min_amount,c.max_discount,d;
end; $$;
grant execute on function public.validate_coupon(text,numeric) to anon, authenticated;

