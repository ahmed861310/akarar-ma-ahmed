returns text language plpgsql security definer set search_path=public as $$
declare c text;
begin
  select code into c from public.referral_codes where user_id=auth.uid();
  if c is null then c:='KH-'||upper(substr(replace(auth.uid()::text,'-',''),1,8)); insert into public.referral_codes(user_id,code) values(auth.uid(),c) on conflict(user_id) do nothing; end if;
  return c;
end; $$;
