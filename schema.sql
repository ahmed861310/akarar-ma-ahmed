-- خدماتي V2.1 — مخطط Supabase الآمن
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  phone text unique not null,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.service_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  service text not null,
  note text not null,
  status text not null default 'قيد المراجعة' check (status in ('قيد المراجعة','جاري التنفيذ','تم التنفيذ','ملغي')),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.service_requests enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin'); $$;

-- مهم: المستخدم يستطيع إنشاء ملفه، لكنه لا يستطيع تعديل الدور أو رقم الهاتف.
