-- V5.1: الدفع الحقيقي الآمن — جلسة دفع + Webhook
create table if not exists public.payment_orders (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.service_requests(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(12,2) not null check (amount >= 0),
  currency text not null default 'EGP',
  coupon_code text,
  status text not null default 'created' check (status in ('created','pending','paid','failed','refunded')),
  external_id text unique,
  checkout_url text,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);
alter table public.payment_orders enable row level security;
drop policy if exists "payment orders own read" on public.payment_orders;
create policy "payment orders own read" on public.payment_orders for select using (user_id = auth.uid() or public.is_admin());

create or replace function public.create_payment_order(p_request_id bigint, p_coupon_code text default null)
returns bigint language plpgsql security definer set search_path = public
as $$
declare r public.service_requests; total numeric; discount numeric := 0; oid bigint;
begin
  select * into r from public.service_requests where id=p_request_id and user_id=auth.uid() for update;
  if not found then raise exception 'الطلب غير موجود'; end if;
  if r.provider_id is null then raise exception 'الطلب غير مرتبط بمقدم خدمة'; end if;
  if r.payment_status in ('held','released') then raise exception 'الطلب مدفوع بالفعل'; end if;
  total := coalesce(r.provider_price,0) + coalesce(r.platform_fee,0);
  if total <= 0 then raise exception 'قيمة الدفع غير صحيحة'; end if;
  if p_coupon_code is not null and length(trim(p_coupon_code)) > 0 then
    select coalesce(discount,0) into discount from public.validate_coupon(upper(trim(p_coupon_code)), coalesce(r.provider_price,0)) limit 1;
  end if;
  total := greatest(0,total-discount);
  insert into public.payment_orders(request_id,user_id,amount,coupon_code,status) values(p_request_id,auth.uid(),total,nullif(upper(trim(p_coupon_code)),''),'created') returning id into oid;
  return oid;
end; $$;
grant execute on function public.create_payment_order(bigint,text) to authenticated;

create or replace function public.confirm_payment_webhook(p_external_id text, p_status text, p_amount numeric)
returns boolean language plpgsql security definer set search_path = public
as $$
declare o public.payment_orders;
begin
  select * into o from public.payment_orders where external_id=p_external_id for update;
  if not found then raise exception 'payment order not found'; end if;
  if o.status='paid' then return true; end if;
  if abs(o.amount-p_amount) > 0.01 then raise exception 'amount mismatch'; end if;
  if lower(p_status)='paid' then
    update public.payment_orders set status='paid',paid_at=now() where id=o.id;
    update public.service_requests set payment_status='held' where id=o.request_id and user_id=o.user_id and payment_status='pending';
    insert into public.wallet_transactions(user_id,type,amount,request_id,note) values(o.user_id,'payment',-o.amount,o.request_id,'دفع مؤكد عبر بوابة الدفع');
  elsif lower(p_status) in ('failed','refunded') then
    update public.payment_orders set status=lower(p_status) where id=o.id;
  end if;
  return true;
end; $$;
-- هذه الدالة تستدعى من Edge Function باستخدام service_role، ولا تمنح للمستخدمين.
revoke all on function public.confirm_payment_webhook(text,text,numeric) from public, anon, authenticated;
