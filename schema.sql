create or replace function public.notify_request_events()
returns trigger language plpgsql security definer set search_path = public
as $$
declare provider_user uuid;
begin
  if TG_OP = 'INSERT' then
    if NEW.provider_id is not null then
      select user_id into provider_user from public.providers where id = NEW.provider_id;
      if provider_user is not null then
        insert into public.notifications(user_id,title,body,type)
        values(provider_user,'طلب خدمة جديد','وصل طلب جديد لك برقم #'||NEW.id||' — راجع الطلب وابدأ التنفيذ.','request');
      end if;
    end if;
  elsif TG_OP = 'UPDATE' then
    if NEW.status is distinct from OLD.status then
      insert into public.notifications(user_id,title,body,type)
      values(NEW.user_id,'تحديث حالة الطلب','تم تغيير حالة طلبك #'||NEW.id||' إلى «'||NEW.status||'».','status');
    end if;
    if NEW.payment_status is distinct from OLD.payment_status and NEW.payment_status in ('released','refunded') then
      if NEW.payment_status='released' then
        select user_id into provider_user from public.providers where id=NEW.provider_id;
        if provider_user is not null then
          insert into public.notifications(user_id,title,body,type)
          values(provider_user,'تم تحرير أرباحك','تم تأكيد استلام الطلب #'||NEW.id||' وتم تحرير مستحقاتك.','earning');
        end if;
      elsif NEW.payment_status='refunded' then
        insert into public.notifications(user_id,title,body,type)
        values(NEW.user_id,'تم استرداد المبلغ','تم استرداد مبلغ الطلب #'||NEW.id||' إلى محفظتك.','refund');
      end if;
    end if;
  end if;
  return NEW;
end; $$;

drop trigger if exists trg_notify_request_events on public.service_requests;
create trigger trg_notify_request_events
after insert or update of status,payment_status on public.service_requests
for each row execute function public.notify_request_events();

