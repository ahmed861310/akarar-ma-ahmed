create or replace function public.create_payment_order(p_request_id bigint, p_coupon_code text default null, p_idempotency_key text default null)
returns bigint language plpgsql security definer set search_path = public
as $$
declare r public.service_requests; total numeric; discount numeric := 0; oid bigint; existing bigint;
begin
  if p_idempotency_key is not null and length(trim(p_idempotency_key)) > 120 then raise exception 'invalid idempotency key'; end if;
  if p_idempotency_key is not null then
    select id into existing from public.payment_orders where user_id=auth.uid() and idempotency_key=trim(p_idempotency_key) limit 1;
    if existing is not null then return existing; end if;
  end if;
  select * into r from public.service_requests where id=p_request_id and user_id=auth.uid() for update;
  if not found then raise exception 'الطلب غير موجود'; end if;
  if r.provider_id is null then raise exception 'الطلب غير مرتبط بمقدم خدمة'; end if;
  if r.payment_status in ('held','released') then raise exception 'الطلب مدفوع بالفعل'; end if;
  total := coalesce(r.provider_price,0) + coalesce(r.platform_fee,0);
  if total <= 0 then raise exception 'قيمة الدفع غير صحيحة'; end if;
  if p_coupon_code is not null and length(trim(p_coupon_code)) > 0 then
    select coalesce(discount,0) into discount from public.validate_coupon(upper(trim(p_coupon_code)), coalesce(r.provider_price,0)) limit 1;
  end if;
  total := greatest(0,total-discount);
  insert into public.payment_orders(request_id,user_id,amount,coupon_code,status,idempotency_key)
  values(p_request_id,auth.uid(),total,nullif(upper(trim(p_coupon_code)),''),'created',nullif(trim(p_idempotency_key),'')) returning id into oid;
  return oid;
exception when unique_violation then
  select id into existing from public.payment_orders where user_id=auth.uid() and idempotency_key=trim(p_idempotency_key) limit 1;
  if existing is not null then return existing; end if;
  raise;
end; $$;
