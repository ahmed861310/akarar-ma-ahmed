create or replace function public.get_platform_metrics()
returns table(
  total_requests bigint,
  completed_requests bigint,
  held_amount numeric,
  released_amount numeric,
  pending_withdrawals bigint,
  open_withdrawal_amount numeric,
  platform_fees numeric
) language sql security definer set search_path=public
as $$
  select
    (select count(*) from public.service_requests),
    (select count(*) from public.service_requests where status='تم التنفيذ'),
    coalesce((select sum(provider_price) from public.service_requests where payment_status='held'),0),
    coalesce((select sum(provider_price) from public.service_requests where payment_status='released'),0),
    (select count(*) from public.withdrawal_requests where status='قيد المراجعة'),
    coalesce((select sum(amount) from public.withdrawal_requests where status='قيد المراجعة'),0),
    coalesce((select sum(platform_fee) from public.service_requests where payment_status='released'),0)
  where public.is_admin();
$$;
grant execute on function public.get_platform_metrics() to authenticated;
