create or replace function public.admin_resolve_dispute(p_dispute_id bigint,p_action text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare d public.disputes; r public.service_requests;
begin
  if not public.is_admin() then raise exception 'غير مصرح'; end if;
  if p_action not in ('investigate','release','refund','dismiss') then raise exception 'قرار غير صالح'; end if;
  select * into d from public.disputes where id=p_dispute_id for update;
  if not found then raise exception 'النزاع غير موجود'; end if;
  if d.request_id is not null then select * into r from public.service_requests where id=d.request_id for update; end if;
  if p_action='release' then
    if r.id is null then raise exception 'النزاع غير مرتبط بطلب'; end if;
    if r.payment_status <> 'held' then raise exception 'لا يوجد مبلغ محجوز قابل للتحرير'; end if;
    if r.status <> 'تم التنفيذ' then raise exception 'لا يمكن تحرير المبلغ قبل اكتمال الطلب'; end if;
    perform public.release_request_payment(r.id);
    update public.disputes set status='resolved',reviewed_at=now() where id=d.id;
  elsif p_action='refund' then
    if r.id is null then raise exception 'النزاع غير مرتبط بطلب'; end if;
    if r.payment_status <> 'held' then raise exception 'لا يوجد مبلغ محجوز قابل للاسترداد'; end if;
    perform public.refund_request_payment(r.id);
    update public.disputes set status='resolved',reviewed_at=now() where id=d.id;
  elsif p_action='investigate' then
    update public.disputes set status='investigating',reviewed_at=null where id=d.id;
  else
    update public.disputes set status='dismissed',reviewed_at=now() where id=d.id;
  end if;
  insert into public.notifications(user_id,title,body,type) values(d.user_id,'تحديث النزاع','تم تحديث حالة النزاع #'||d.id||'.','system');
  if d.provider_id is not null then insert into public.notifications(user_id,title,body,type) select p.user_id,'تحديث نزاع على طلب','تم تحديث حالة النزاع #'||d.id||'.','system' from public.providers p where p.id=d.provider_id; end if;
  return jsonb_build_object('ok',true,'message','تم تنفيذ القرار بنجاح');
end; $$;
revoke all on function public.admin_resolve_dispute(bigint,text) from public,anon,authenticated;
grant execute on function public.admin_resolve_dispute(bigint,text) to authenticated;

