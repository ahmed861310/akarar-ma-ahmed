-- V2.2: سوق مقدمي الخدمات
create table if not exists public.providers (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  category text not null,
  description text not null,
  price numeric(12,2) not null check (price >= 0),
  contact text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.providers enable row level security;

alter table public.service_requests add column if not exists provider_id bigint references public.providers(id) on delete set null;

 drop policy if exists "providers public read active" on public.providers;
 drop policy if exists "providers own insert" on public.providers;
 drop policy if exists "providers own update" on public.providers;
create policy "providers public read active" on public.providers for select using (active = true or user_id = auth.uid() or public.is_admin());
create policy "providers own insert" on public.providers for insert with check (user_id = auth.uid());
create policy "providers own update" on public.providers for update using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());

 drop policy if exists "requests own read" on public.service_requests;
create policy "requests own read" on public.service_requests for select using (user_id = auth.uid() or public.is_admin());

-- V2.3: ملفات مقدمي الخدمات + التقييمات + تتبع العمولة
alter table public.providers add column if not exists commission_rate numeric(5,2) not null default 10 check (commission_rate >= 0 and commission_rate <= 100);
alter table public.service_requests add column if not exists provider_price numeric(12,2);
alter table public.service_requests add column if not exists platform_fee numeric(12,2) not null default 0;

create table if not exists public.provider_reviews (
  id bigint generated by default as identity primary key,
  provider_id bigint not null references public.providers(id) on delete cascade,
  request_id bigint not null unique references public.service_requests(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now()
);
alter table public.provider_reviews enable row level security;
drop policy if exists "reviews public read" on public.provider_reviews;
drop policy if exists "reviews own insert" on public.provider_reviews;
create policy "reviews public read" on public.provider_reviews for select using (true);
create policy "reviews own insert" on public.provider_reviews for insert with check (
  user_id = auth.uid() and exists (
    select 1 from public.service_requests r
    where r.id = request_id and r.user_id = auth.uid() and r.provider_id = provider_id and r.status = 'تم التنفيذ'
  )
);

create or replace function public.get_provider_stats(p_provider_id bigint)
returns table(completed bigint, reviews bigint, average numeric)
language sql stable security definer set search_path = public
as $$
  select
    (select count(*) from public.service_requests r where r.provider_id = p_provider_id and r.status='تم التنفيذ'),
    (select count(*) from public.provider_reviews v where v.provider_id = p_provider_id),
    coalesce((select round(avg(v.rating)::numeric,1) from public.provider_reviews v where v.provider_id = p_provider_id),0);
$$;

grant execute on function public.get_provider_stats(bigint) to anon, authenticated;
