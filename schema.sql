create or replace function public.get_provider_stats(p_provider_id bigint)
returns table(completed bigint, reviews bigint, average numeric)
language sql stable security definer set search_path = public
as $$
  select
    (select count(*) from public.service_requests r where r.provider_id = p_provider_id and r.status='تم التنفيذ'),
    (select count(*) from public.provider_reviews v where v.provider_id = p_provider_id),
    coalesce((select round(avg(v.rating)::numeric,1) from public.provider_reviews v where v.provider_id = p_provider_id),0);
$$;

grant execute on function public.get_provider_stats(bigint) to anon, authenticated;

