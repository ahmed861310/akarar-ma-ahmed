create or replace function public.provider_trust_score(p_provider_id bigint)
returns table(score integer, level text, risk_penalty integer)
language sql stable security definer set search_path=public
as $$
with p as (select * from public.providers where id=p_provider_id),
r as (select coalesce(avg(rating),0) avg_rating,count(*) review_count from public.provider_ratings where provider_id=p_provider_id),
c as (select count(*) filter(where status='تم التنفيذ') completed from public.service_requests where provider_id=p_provider_id),
risk as (select greatest(0,least(25,coalesce(sum(points),0))) penalty from public.provider_risk_events where provider_id=p_provider_id)
select greatest(0,least(100,round(35+r.avg_rating*9+least(5,r.review_count)*2+least(5,c.completed)*2+case when p.verified then 10 else 0 end-risk.penalty)::int)),
case when round(35+r.avg_rating*9+least(5,r.review_count)*2+least(5,c.completed)*2+case when p.verified then 10 else 0 end-risk.penalty)>=85 then 'ممتاز' when round(35+r.avg_rating*9+least(5,r.review_count)*2+least(5,c.completed)*2+case when p.verified then 10 else 0 end-risk.penalty)>=70 then 'موثوق' when round(35+r.avg_rating*9+least(5,r.review_count)*2+least(5,c.completed)*2+case when p.verified then 10 else 0 end-risk.penalty)>=50 then 'جيد' else 'يحتاج مراجعة' end,
risk.penalty from p,r,c,risk;
$$;
revoke all on function public.provider_trust_score(bigint) from public, anon; grant execute on function public.provider_trust_score(bigint) to authenticated;

